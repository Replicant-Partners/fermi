//! Agent taxonomy — derived ranks (SPEC_30).
//!
//! # Why this exists in Rust as well as Python
//!
//! `scripts/taxonomy.py` is the editorial tool: it audits the on-disk
//! `agent_card.json` corpus and helps a human fill the ranks that need a
//! human. But taxonomy previously lived *only* in those files, which meant
//! every agent created through the UI or the import endpoint could never be
//! classified at all — no card on disk, nothing to read. All 13 efra agents
//! sat under `Incertae sedis` permanently, and that is the majority shape
//! of third-party agents.
//!
//! So the derived ranks are computed here too, at creation time, writing
//! into `agents.taxonomy` (mig-186). An agent authored through the API is
//! classified the moment it exists.
//!
//! # The drift hazard, and what guards it
//!
//! Two implementations of one rule will diverge. That is not a hypothetical
//! — this codebase has already been bitten by a duplicated predicate
//! (`test_agent_` filtering was inline in several handlers and missing from
//! others, so the Observatory opened on a wall of test rows).
//!
//! The guard is `tests/taxonomy_parity.rs`, which reads
//! `agents/taxonomy_derived_expected.json` — regenerated by the Python tool
//! — and asserts this module produces identical output for every card in
//! the corpus. If either side changes a rule, the test fails.
//!
//! Editorial ranks (kingdom, family, genus) are deliberately absent. A name
//! is a claim about kinship; deriving one would be guessing convincingly.

use serde_json::{json, Value};

/// The seven ranks, in canonical order.
pub const RANKS: [&str; 7] = [
    "kingdom", "phylum", "class", "order", "family", "genus", "species",
];

/// Ranks this module can compute from the agent itself.
pub const DERIVED: [&str; 4] = ["phylum", "class", "order", "species"];

/// Ranks that require a human, drawn from `agents/taxonomy_vocab.json`.
pub const EDITORIAL: [&str; 3] = ["kingdom", "family", "genus"];

/// `class` ← `agent_type`, one-to-one. Keeps the rank verifiable: a card
/// whose stated class disagrees with its type is a detectable defect
/// rather than a matter of taste.
pub fn class_for(agent_type: &str) -> Option<&'static str> {
    Some(match agent_type.to_ascii_lowercase().as_str() {
        "research" => "Researchia",
        "creative" => "Creativia",
        "meta" => "Metaria",
        "observability" => "Vigilia",
        "coherence" => "Cohaerentia",
        "commerce" => "Mercatia",
        "strategist" => "Strategia",
        "compound" => "Compositia",
        "coordination" => "Coordinia",
        "game" => "Ludia",
        "companion" => "Compandia",
        "analytics" => "Analytia",
        "forecast" => "Prognostia",
        _ => return None,
    })
}

/// `order` ← output modality, matched by substring against the agent's
